/* 空き枠算出のテスト。akima.html の AKIMA-CORE ブロックを *そのまま* 切り出して回すので、
   ロジックの写しがどこにも増えない（＝テストと本番がずれない）。
   実行: cd ~/制作物/akima-src && node test-slots.mjs                                     */
import { readFileSync } from 'node:fs';

const html = readFileSync('../akima.html', 'utf8');
const a = html.indexOf('const AKIMA = (function(){');
const b = html.indexOf('/* ==== AKIMA-CORE:END ==== */');
if (a < 0 || b < 0) { console.error('akima.html から AKIMA-CORE ブロックを切り出せなかった'); process.exit(1); }
const AKIMA = new Function(html.slice(a, b) + '\nreturn AKIMA;')();

let ok = 0, ng = 0;
const eq = (name, got, want) => {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) ok++;
  else { ng++; console.log(`  ✗ ${name}\n      期待: ${w}\n      実際: ${g}`); }
};

const T = s => Date.parse(s);                        // '2026-08-03T09:00:00+09:00'
const NOW = T('2026-08-03T08:00:00+09:00');          // 月曜の朝8時に立っている想定
const win = (from, to, onDays) => [0,1,2,3,4,5,6].map(wd => ({
  on: onDays ? onDays.indexOf(wd) >= 0 : true, from, to,
}));
const busy = (s, e, extra) => Object.assign({ startMs: T(s), endMs: T(e), allDay: false, kind: 'work' }, extra || {});

/** 結果を「8/3: 9:00〜22:00 [9:00,10:00]」のような読める形にする（[]の中は候補の開始時刻） */
function show(days) {
  return days.map(d => `${d.m}/${d.d}: ` + d.spans.map(sp =>
    AKIMA.fmtRange(sp) + ' [' +
    sp.starts.map(t => AKIMA.hmText(Math.round((t - d.dayMs) / 60000))).join(',') + ']'
  ).join(' | '));
}
function run(o) {
  const opt = Object.assign({
    nowMs: NOW, busy: [], days: 3, durationMin: 45, bufferMin: 60,
    windows: win('09:00', '22:00'), allDayBusy: true, ignoreKinds: [],
    morning: { on: false, workOnly: true, lateEndFrom: '20:00', until: '12:00' },
    leadMin: 0, snapMin: 15, startStepMin: 60, maxStartsPerSpan: 4,
  }, o);
  return { days: AKIMA.computeSlots(opt), opt };
}
const R = o => show(run(o).days);

