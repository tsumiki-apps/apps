// クリップボードを見張って履歴に足す（Watcher）、選んだものを貼る（Paster）、順番に貼る（Stack）。
import AppKit
import ApplicationServices

// MARK: - 見張る

final class Watcher {
    let store: Store
    let pb: NSPasteboard
    private var lastCount: Int
    /// 自分で書いたときの番号（自分の書き込みは履歴に足さない）。直前の他のコピーを取りこぼさないよう、書く前に一度読む
    var ownCounts: Set<Int> = []
    /// 前に見たときの手前のアプリ（パスワード管理アプリでコピーしてすぐ切り替えても記録しないため）
    private var prevFront: String?
    /// これより大きいものは記録しない（固まる・ふくらむのを防ぐ）
    static let maxText = 1_000_000, maxImage = 30_000_000
    var onCapture: ((Clip) -> Void)?
    private var timer: Timer?

    init(store: Store, pb: NSPasteboard = .general) {
        self.store = store; self.pb = pb
        lastCount = pb.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in self?.tick() }
        timer?.tolerance = 0.1
    }

    /// 変更番号が変わったときだけ中身を読む
    func tick(app: String? = nil, appName: String? = nil) {
        let n = pb.changeCount
        let front = NSWorkspace.shared.frontmostApplication
        let nowApp = app ?? front?.bundleIdentifier
        let before = prevFront
        prevFront = nowApp
        guard n != lastCount else { return }
        lastCount = n
        if ownCounts.contains(n) || Prefs.paused { return }
        if let before, Prefs.ignored.contains(before) { return }
        guard let c = Watcher.read(pb, app: nowApp, appName: appName ?? front?.localizedName) else { return }
        let clip = store.add(c)
        onCapture?(clip)
    }

    /// 「隠す」「一時的」「自動で作った」の印。付いていたら中身を読まずに捨てる（nspasteboard.org の決まり＋よく使われる印）
    static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                         "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                                         "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
                                         "com.typeit4me.clipping", "net.antelle.keeweb"]

    static func read(_ pb: NSPasteboard, app: String?, appName: String?, ignored: [String] = Prefs.ignored) -> Captured? {
        let types = (pb.types ?? []).map(\.rawValue)
        if types.isEmpty || types.contains(where: skipTypes.contains) { return nil }
        if let app, ignored.contains(app) { return nil }
        // ファイル（Finder でのコピー）
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return Captured(kind: .file, text: urls.map(\.path).joined(separator: "\n"), app: app, appName: appName)
        }
        // 文字・リンク
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if s.utf8.count > maxText { return nil }
            let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !t.contains(where: \.isWhitespace) && t.count < 4000
                && (URL(string: t)?.scheme.map { ["http", "https"].contains($0.lowercased()) } ?? false)
            var rtf = isLink ? nil : pb.data(forType: .rtf)
            if (rtf?.count ?? 0) > 2_000_000 { rtf = nil }
            return Captured(kind: isLink ? .link : .text, text: s, rtf: rtf, app: app, appName: appName)
        }
        // 画像
        for t in [NSPasteboard.PasteboardType.png, .tiff] {
            guard let d = pb.data(forType: t), d.count <= maxImage, let rep = NSBitmapImageRep(data: d),
                  rep.pixelsWide * rep.pixelsHigh <= 60_000_000 else { continue }
            let png = t == .png ? d : rep.representation(using: .png, properties: [:])
            guard let png else { continue }
            return Captured(kind: .image, text: "", png: png, width: rep.pixelsWide, height: rep.pixelsHigh, app: app, appName: appName)
        }
        return nil
    }
}

// MARK: - 貼る

enum PasteMode: Equatable { case normal, plain, tidy(Tidy) }

final class Paster {
    let store: Store
    let watcher: Watcher
    static let marker: Int64 = 0x5453_4350        // 自分で送った ⌘V の印（順番に貼るの見張りで無視する）

    init(store: Store, watcher: Watcher) { self.store = store; self.watcher = watcher }

    /// クリップボードに書く（自分の書き込みとして覚える）
    @discardableResult
    func write(_ c: Clip, mode: PasteMode, to pb: NSPasteboard? = nil) -> Bool {
        let pb = pb ?? watcher.pb
        if pb === watcher.pb { watcher.tick() }      // 直前の他のコピーを先に履歴へ
        var imageData: Data?
        if c.kind == .image {
            guard let u = store.imageURL(c), let d = try? Data(contentsOf: u) else { NSSound.beep(); return false }   // 画像が無いならクリップボードを空にしない
            imageData = d
        }
        pb.clearContents()
        switch c.kind {
        case .text, .link:
            var s = c.text
            if case .tidy(let t) = mode { s = t.apply(s) }
            pb.setString(s, forType: .string)
            if mode == .normal, let rtf = store.richData(c) { pb.setData(rtf, forType: .rtf) }
        case .image:
            if let d = imageData {
                if let img = NSImage(data: d) { pb.writeObjects([img]) }
                pb.setData(d, forType: .png)
            }
        case .file:
            pb.writeObjects(c.files.map { $0 as NSURL })
        }
        watcher.ownCounts.insert(pb.changeCount)
        return true
    }

    /// 選んだものを前のアプリに貼る。アクセシビリティの許可がなければクリップボードに入れるだけ
    func paste(_ c: Clip, mode: PasteMode) {
        Debug.log("paste kind=\(c.kind)")
        guard write(c, mode: mode) else { return }
        store.touch(c.id)
        guard Paster.trusted(prompt: !Paster.asked) else { Paster.asked = true; return }
        Paster.whenOtherAppFront { Paster.postCommandV() }
    }

    /// 許可の案内は起動中に1回だけ出す（貼るたびに出さない）
    static var asked = false

    /// 元のアプリが手前に戻ってから ⌘V を送る（戻る前に送ると自分に届く）。最大 0.6 秒待ち、戻らなければ送らない
    static func whenOtherAppFront(_ tries: Int = 0, _ f: @escaping () -> Void) {
        let front = NSWorkspace.shared.frontmostApplication?.processIdentifier
        if front != nil && front != getpid() {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.05, execute: f)
        } else if tries >= 12 {
            return
        } else {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { whenOtherAppFront(tries + 1, f) }
        }
    }

    static func trusted(prompt: Bool) -> Bool {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: prompt] as CFDictionary
        return AXIsProcessTrustedWithOptions(opts)
    }

    static func postCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        src?.userData = marker
        let v = CGKeyCode(9)      // V（US・JIS とも同じ位置）
        for down in [true, false] {
            let e = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: down)
            e?.flags = .maskCommand
            e?.post(tap: .cghidEventTap)
        }
    }
}

// MARK: - 順番に貼る（オンの間にコピーしたものを、⌘V を押すたびに1つずつ前から貼る）

final class Stack {
    let paster: Paster
    private(set) var on = false
    private(set) var queue: [Clip] = []
    private(set) var index = 0
    var onUpdate: (() -> Void)?
    private var tap: CFMachPort?
    private var source: CFRunLoopSource?
    static weak var current: Stack?

    init(paster: Paster) { self.paster = paster }

    var remaining: Int { queue.count - index }

    func toggle() { if on { stop() } else { start() } }

    @discardableResult
    func start() -> Bool {
        guard Paster.trusted(prompt: false) else { return false }
        queue = []; index = 0; syncHold()
        Stack.current = self
        let mask = CGEventMask(1 << CGEventType.keyDown.rawValue)
        tap = CGEvent.tapCreate(tap: .cgSessionEventTap, place: .headInsertEventTap, options: .defaultTap, eventsOfInterest: mask,
                                callback: { _, type, e, _ in
                                    if type == .tapDisabledByTimeout || type == .tapDisabledByUserInput {
                                        if let t = Stack.current?.tap { CGEvent.tapEnable(tap: t, enable: true) }
                                        return Unmanaged.passUnretained(e)
                                    }
                                    Stack.current?.keyDown(e)
                                    return Unmanaged.passUnretained(e)
                                }, userInfo: nil)
        guard let tap else { return false }
        source = CFMachPortCreateRunLoopSource(nil, tap, 0)
        CFRunLoopAddSource(CFRunLoopGetMain(), source, .commonModes)
        CGEvent.tapEnable(tap: tap, enable: true)
        on = true
        onUpdate?()
        return true
    }

    private func syncHold() { paster.store.hold = Set(queue.map(\.id)) }

    /// テスト用（イベントの見張りなし）
    func setOnForTest() { queue = []; index = 0; on = true }

    func stop() {
        if let tap { CGEvent.tapEnable(tap: tap, enable: false) }
        if let source { CFRunLoopRemoveSource(CFRunLoopGetMain(), source, .commonModes) }
        tap = nil; source = nil
        on = false; queue = []; index = 0; syncHold()
        onUpdate?()
    }

    /// オンの間にコピーしたもの
    func add(_ c: Clip) {
        guard on else { return }
        queue.append(c); syncHold()
        onUpdate?()
    }

    /// ⌘V が押された（自分で送ったものは除く）。届く前にクリップボードを次のものに替える
    private func keyDown(_ e: CGEvent) {
        guard e.getIntegerValueField(.eventSourceUserData) != Paster.marker else { return }
        let f = e.flags.intersection([.maskCommand, .maskShift, .maskAlternate, .maskControl])
        guard f == .maskCommand, e.getIntegerValueField(.keyboardEventKeycode) == 9, e.getIntegerValueField(.keyboardEventAutorepeat) == 0 else { return }
        // 自分の窓（帯の検索・設定）での ⌘V では進めない
        if NSWorkspace.shared.frontmostApplication?.processIdentifier == getpid() { return }
        next()
    }

    /// 次のものをクリップボードへ（テストからも呼ぶ）。最後まで貼ったら少し待って終わる
    func next(to pb: NSPasteboard? = nil) {
        guard index < queue.count else { return }
        let c = paster.store.clips.first { $0.id == queue[index].id } ?? queue[index]    // 最新の中身で
        paster.write(c, mode: .normal, to: pb)
        index += 1
        onUpdate?()
        if index >= queue.count {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.4) { [weak self] in
                guard let self, self.on, self.index >= self.queue.count else { return }
                self.stop()
            }
        }
    }
}
