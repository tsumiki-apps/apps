// 自己テスト（build.sh が毎回走らせる）。本物のクリップボード・本物の履歴・本物の設定には触らない：
// 置き場は一時フォルダ、クリップボードは名前つきの別のもの、設定は別の UserDefaults。中身は架空の文字だけ。
import AppKit
import Carbon

enum SelfTest {
    static var ok = true
    static func check(_ cond: Bool, _ name: String) {
        print(cond ? "✓ \(name)" : "✗ \(name)")
        if !cond { ok = false }
    }

    static func sandbox() -> (Store, NSPasteboard, URL) {
        let suite = "com.tsumiki.clip.selftest"
        UserDefaults().removePersistentDomain(forName: suite)
        Prefs.d = UserDefaults(suiteName: suite)!
        Shortcuts.defaults = Prefs.d
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("tsumiki-clip-test-\(getpid())-\(UUID().uuidString.prefix(6))")
        let pb = NSPasteboard(name: .init("com.tsumiki.clip.selftest.\(getpid())"))
        pb.clearContents()
        return (Store(root: dir), pb, dir)
    }

    static func run() -> Bool {
        let (store, pb, dir) = sandbox()
        defer { try? FileManager.default.removeItem(at: dir); pb.releaseGlobally() }
        let w = Watcher(store: store, pb: pb)
        let paster = Paster(store: store, watcher: w)
        func copy(_ s: String, extra: [String] = [], app: String = "com.example.editor") {
            pb.clearContents()
            pb.declareTypes([.string] + extra.map { .init($0) }, owner: nil)
            pb.setString(s, forType: .string)
            for t in extra { pb.setData(Data(), forType: .init(t)) }
            w.tick(app: app, appName: "架空エディタ")
        }

        // 記録する・しない
        copy("架空の会議メモ：14時から第2会議室")
        check(store.clips.count == 1 && store.clips[0].kind == .text && store.clips[0].app == "com.example.editor", "文字を記録（アプリも覚える）")
        copy("https://example.com/menu?id=1")
        check(store.clips[0].kind == .link, "リンクを見分ける")
        copy("example.com と https://example.com")
        check(store.clips[0].kind == .text, "文中のリンクは文字のまま")
        let before = store.clips.count
        copy("架空のパスワード Xy7-dummy", extra: ["org.nspasteboard.ConcealedType"])
        check(store.clips.count == before, "隠す印（ConcealedType）は記録しない")
        copy("架空の一時的な文字", extra: ["org.nspasteboard.TransientType"])
        check(store.clips.count == before, "一時的の印（TransientType）は記録しない")
        copy("架空の自動の文字", extra: ["org.nspasteboard.AutoGeneratedType"])
        check(store.clips.count == before, "自動の印（AutoGeneratedType）は記録しない")
        copy("架空の口座 0000000", app: "com.1password.1password")
        check(store.clips.count == before, "記録しないアプリ（既定のパスワード管理）からは記録しない")
        Prefs.ignored = Prefs.ignored + ["com.example.secret"]
        copy("架空の秘密", app: "com.example.secret")
        check(store.clips.count == before, "足した記録しないアプリからも記録しない")
        Prefs.paused = true
        copy("一時停止中の架空の文字")
        check(store.clips.count == before, "一時停止中は記録しない")
        Prefs.paused = false

        // 同じものは1つにまとめて一番上へ
        copy("架空の会議メモ：14時から第2会議室")
        check(store.clips.count == before && store.clips[0].text.hasPrefix("架空の会議メモ"), "同じ文字は1つにまとめて一番上へ")

        // ファイル
        let f = dir.appendingPathComponent("架空の見積もり.txt")
        try? "dummy".write(to: f, atomically: true, encoding: .utf8)
        pb.clearContents(); pb.writeObjects([f as NSURL]); w.tick(app: "com.apple.finder", appName: "Finder")
        check(store.clips[0].kind == .file && store.clips[0].files.first?.lastPathComponent == "架空の見積もり.txt", "ファイルを記録")

        // 画像
        let img = NSImage(size: NSSize(width: 40, height: 30), flipped: false) { r in NSColor.orange.setFill(); r.fill(); return true }
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 40, pixelsHigh: 30, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                                   isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        NSGraphicsContext.saveGraphicsState(); NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        img.draw(in: NSRect(x: 0, y: 0, width: 40, height: 30)); NSGraphicsContext.restoreGraphicsState()
        pb.clearContents(); pb.setData(rep.tiffRepresentation!, forType: .tiff); w.tick(app: "com.example.paint", appName: "架空ペイント")
        let ic = store.clips[0]
        check(ic.kind == .image && ic.width == 40 && ic.height == 30 && store.imageURL(ic).map { FileManager.default.fileExists(atPath: $0.path) } == true,
              "画像を PNG で記録（大きさも）")

        // 自分の書き込みは記録しない
        let n0 = store.clips.count
        paster.write(store.clips[1], mode: .normal)
        w.tick(app: "com.example.editor", appName: nil)
        check(store.clips.count == n0, "自分で書いたものは記録し直さない")

        // 書式つき（RTF）：ふつうは書式ごと、書式なし・整えるは文字だけ
        let rtf = NSAttributedString(string: "架空の太字", attributes: [.font: NSFont.boldSystemFont(ofSize: 14)])
            .rtf(from: NSRange(location: 0, length: 5), documentAttributes: [:])!
        pb.clearContents(); pb.declareTypes([.string, .rtf], owner: nil); pb.setString("架空の太字", forType: .string); pb.setData(rtf, forType: .rtf)
        w.tick(app: "com.example.editor", appName: nil)
        let rc = store.clips[0]
        check(rc.rich != nil, "書式つき（RTF）も覚える")
        paster.write(rc, mode: .normal); check(pb.data(forType: .rtf) != nil, "ふつうに貼ると書式つき")
        paster.write(rc, mode: .plain); check(pb.data(forType: .rtf) == nil && pb.string(forType: .string) == "架空の太字", "書式なしで貼ると文字だけ")

        // 整える
        check(Tidy.trim.apply("  架空の文字　 \n 次の行  \n\n") == "架空の文字\n 次の行", "前後の空白を取る（行末も）")
        check(Tidy.join.apply("架空の\n文章です\n") == "架空の文章です", "改行をつなぐ（日本語はそのまま）")
        check(Tidy.join.apply("This is\na dummy\r\nline.") == "This is a dummy line.", "改行をつなぐ（英語は空白を入れる）")
        check(Tidy.halfwidth.apply("ＡＢＣ１２３（カタカナ）。") == "ABC123（カタカナ）。", "全角英数を半角に（かっこ・カナはそのまま）")
        copy("  ＴＥＳＴ　ｃｏｄｅ  ")
        paster.write(store.clips[0], mode: .tidy(.halfwidth))
        check(pb.string(forType: .string) == "  TEST　code  ", "整えて貼るでクリップボードに入る中身")

        // 検索
        copy("Dummy Café 架空の店")
        check(store.list(board: nil, query: "ｄｕｍｍｙ").first?.text == "Dummy Café 架空の店", "検索は全角半角・大文字小文字を区別しない")
        check(store.list(board: nil, query: "cafe 架空").count == 1, "検索は空白で区切ると全部を含むもの")
        check(store.list(board: nil, query: "架空エディタ").count >= 1, "検索はアプリの名前でも")
        check(store.list(board: nil, query: "存在しない語").isEmpty, "当たらない検索は空")

        // ピンボード
        let b = store.addBoard("定型文")
        let src = store.clips.first { $0.kind == .image }!
        let pinned = store.pin(src.id, to: b.id)!
        check(store.list(board: b.id, query: "").count == 1 && pinned.image != src.image, "ピンボードへ写す（画像も別に持つ）")
        store.pin(src.id, to: b.id)
        check(store.list(board: b.id, query: "").count == 1, "同じものは2回入れない")
        store.remove(src.id)
        check(store.imageURL(pinned).map { FileManager.default.fileExists(atPath: $0.path) } == true, "履歴から消してもピンの画像は残る")
        store.rename(pinned.id, "架空のロゴ")
        check(store.list(board: b.id, query: "ロゴ").count == 1, "名前を付けると名前で探せる")

        // 期間と件数
        Prefs.keepDays = 30
        store.add(Captured(kind: .text, text: "40日前の架空の文字"), now: Date().addingTimeInterval(-40 * 86400))
        store.purge()
        check(!store.clips.contains { $0.text == "40日前の架空の文字" }, "期間を過ぎた履歴は消える")
        check(store.list(board: b.id, query: "").count == 1, "ピンボードは期間で消えない")
        Prefs.maxCount = 3
        for i in 1...5 { store.add(Captured(kind: .text, text: "架空の\(i)件目")) }
        let hist = store.list(board: nil, query: "")
        check(hist.count == 3 && hist[0].text == "架空の5件目", "件数の上限で古いものから消える")
        Prefs.maxCount = 1000

        // 守り：フォルダとファイルは自分だけ
        let fm = FileManager.default
        let dperm = (try? fm.attributesOfItem(atPath: dir.path)[.posixPermissions] as? Int) ?? 0
        let fperm = (try? fm.attributesOfItem(atPath: dir.appendingPathComponent("clips.json").path)[.posixPermissions] as? Int) ?? 0
        let iperm = store.imageURL(pinned).flatMap { (try? fm.attributesOfItem(atPath: $0.path)[.posixPermissions] as? Int) } ?? 0
        check(dperm == 0o700 && fperm == 0o600 && iperm == 0o600, "置き場は 0700・ファイルは 0600（自分だけ読める）")

        // 読み直しても同じ
        let again = Store(root: dir)
        check(again.clips.count == store.clips.count && again.boards == store.boards, "終了して開き直しても同じ中身")

        // 全部消す（ピンボードは残す）
        store.clearHistory()
        check(store.list(board: nil, query: "").isEmpty && store.list(board: b.id, query: "").count == 1, "履歴を全部消してもピンボードは残る")
        let leftovers = ((try? fm.contentsOfDirectory(atPath: dir.appendingPathComponent("images").path)) ?? []).count
        check(leftovers == 1, "消した画像のファイルも消える（残るのはピンの1つ）")

        // 順番に貼る：集めた順に1つずつ
        let st = Stack(paster: paster)
        let q = ["架空の1つ目", "架空の2つ目", "架空の3つ目"].map { store.add(Captured(kind: .text, text: $0)) }
        st.forceOn(); q.forEach(st.add)
        var got: [String] = []
        for _ in 0..<4 { st.next(to: pb); got.append(pb.string(forType: .string) ?? "") }
        check(got == ["架空の1つ目", "架空の2つ目", "架空の3つ目", "架空の3つ目"], "順番に貼るは集めた順に1つずつ（最後で止まる）")
        check(st.remaining == 0, "順番に貼るの残り数")

        // 順番に貼る：同じ画像をもう一度コピーしても、待っている分の画像は消えない
        let st2 = Stack(paster: paster)
        st2.forceOn()
        func png(_ c: NSColor) -> Data {
            let r = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 8, pixelsHigh: 8, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                                     isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
            NSGraphicsContext.saveGraphicsState(); NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: r)
            c.setFill(); NSRect(x: 0, y: 0, width: 8, height: 8).fill(); NSGraphicsContext.restoreGraphicsState()
            return r.representation(using: .png, properties: [:])!
        }
        let ia = store.add(Captured(kind: .image, text: "", png: png(.red), width: 8, height: 8)); st2.add(ia)
        st2.add(store.add(Captured(kind: .image, text: "", png: png(.blue), width: 8, height: 8)))
        let ia2 = store.add(Captured(kind: .image, text: "", png: png(.red), width: 8, height: 8)); st2.add(ia2)
        check(ia2.id == ia.id, "同じ画像は同じものとして一番上へ（作り直さない）")
        st2.next(to: pb)
        check(pb.data(forType: .png) != nil, "順番に貼る：同じ画像を2回コピーしても1つ目が貼れる")
        Prefs.maxCount = 1
        store.purge()
        check(store.imageURL(ia).map { FileManager.default.fileExists(atPath: $0.path) } == true, "順番に貼るで待っている分は件数の上限でも消さない")
        Prefs.maxCount = 1000
        st2.stop()
        check(store.hold.isEmpty, "順番に貼るを止めると守りも外れる")

        // 画像のファイルが無いときはクリップボードを空にしない
        pb.clearContents(); pb.setString("架空の残すべき文字", forType: .string)
        check(!paster.write(Clip(kind: .image, text: "", sig: "x", image: "無いファイル.png"), mode: .normal) && pb.string(forType: .string) == "架空の残すべき文字",
              "画像が見つからないときはクリップボードをそのまま")

        // 大きすぎるものは記録しない
        let nBig = store.clips.count
        copy(String(repeating: "架", count: Watcher.maxText / 3 + 10))
        check(store.clips.count == nBig, "大きすぎる文字は記録しない")

        // パスワード管理アプリから切り替えた直後のコピーも記録しない
        copy("架空の切り替え前", app: "com.1password.1password")
        copy("架空の切り替え直後", app: "com.example.editor")
        check(!store.clips.contains { $0.text == "架空の切り替え直後" }, "記録しないアプリから切り替えた直後のコピーは記録しない")
        copy("架空の少しあと", app: "com.example.editor")
        check(store.clips.first?.text == "架空の少しあと", "その次からは記録する")

        // 壊れた履歴ファイルは横へよけ、上書きで消さない
        let bad = fm.temporaryDirectory.appendingPathComponent("tsumiki-clip-bad-\(getpid())")
        try? fm.createDirectory(at: bad.appendingPathComponent("images"), withIntermediateDirectories: true)
        try? Data("{壊れた".utf8).write(to: bad.appendingPathComponent("clips.json"))
        try? Data("x".utf8).write(to: bad.appendingPathComponent("images/残り.png"))
        let bs = Store(root: bad)
        let names = (try? fm.contentsOfDirectory(atPath: bad.path)) ?? []
        check(bs.loadFailed && names.contains { $0.hasPrefix("clips.corrupt-") } && !names.contains("clips.json"), "壊れた履歴はよけて残す")
        check(fm.fileExists(atPath: bad.appendingPathComponent("images/残り.png").path), "読めなかったときは画像も消さない")
        try? fm.removeItem(at: bad)

        // 指されていない画像は起動時に消える
        try? Data("x".utf8).write(to: dir.appendingPathComponent("images/迷子.png"))
        _ = Store(root: dir)
        check(!fm.fileExists(atPath: dir.appendingPathComponent("images/迷子.png").path), "どこからも指されていない画像は起動時に消す")
        let ex = (try? dir.resourceValues(forKeys: [.isExcludedFromBackupKey]))?.isExcludedFromBackup ?? false
        check(ex, "置き場はバックアップに入れない")

        // キー
        check(Shortcuts.combo(1)?.display == "⇧⌘V" && Shortcuts.combo(2)?.display == "⇧⌘C", "既定のキー（⇧⌘V 開く・⇧⌘C 順番に貼る）")
        Shortcuts.set(2, Shortcuts.combo(1))
        check(Shortcuts.combo(1) == nil && Shortcuts.combo(2)?.display == "⇧⌘V", "同じキーを2つに付けると古いほうはなし")
        Shortcuts.resetAll()
        check(KeyCombo.from(code: UInt16(kVK_ANSI_V), flags: [], chars: "v") == nil, "⌘⌃⌥ のないキーは付けられない")

        // 帯（画面）
        for i in 1...12 { store.add(Captured(kind: .text, text: "架空の文字 \(i)")) }
        let strip = Strip(store: store)
        strip.reload()
        for wdt in [1024.0, 1440, 1920, 2560] {
            strip.layout(width: wdt)
            check(strip.panel.contentView!.frame.width == wdt, "帯を幅 \(Int(wdt)) で並べる")
        }
        check(strip.items.first?.text == "架空の文字 12" && strip.items[1].text == "架空の文字 11" && strip.sel == 0, "帯に履歴が新しい順に並ぶ")
        strip.handleKey(code: kVK_RightArrow, flags: []); strip.handleKey(code: kVK_RightArrow, flags: [])
        check(strip.sel == 2, "→ で右へ")
        strip.handleKey(code: kVK_LeftArrow, flags: [])
        check(strip.sel == 1, "← で左へ")
        for _ in 0..<5 { strip.handleKey(code: kVK_LeftArrow, flags: []) }
        check(strip.sel == 0, "左端で止まる")
        var pasted: (String, PasteMode)?
        strip.onPaste = { c, m in pasted = (c.text, m) }
        strip.handleKey(code: kVK_ANSI_3, flags: .command)
        check(pasted?.0 == "架空の文字 10" && pasted?.1 == .normal, "⌘3 で3つ目を貼る")
        strip.handleKey(code: kVK_Return, flags: .shift)
        check(pasted?.1 == .plain, "⇧Enter で書式なし")
        strip.handleKey(code: kVK_RightArrow, flags: .command)
        check(strip.board == b.id && strip.items.count == 1, "⌘→ でピンボードへ")
        strip.handleKey(code: kVK_LeftArrow, flags: .command)
        check(strip.board == nil, "⌘← で履歴へ戻る")
        let n1 = strip.items.count
        strip.handleKey(code: kVK_Delete, flags: .command)
        check(strip.items.count == n1 - 1, "⌘⌫ で1つ消す")
        strip.search.stringValue = "文字 7"
        strip.reload()
        check(strip.items.count == 1, "検索で絞る")
        func tidyEnabled(_ t: String) -> [Bool]? {
            strip.menu(for: Clip(kind: .text, text: t, sig: "")).items.first { $0.title == "整えて貼る" }?.submenu?.items.map(\.isEnabled)
        }
        check(tidyEnabled("架空の文字") == [false, false, false] && tidyEnabled(" ＡＢ\nC ") == [true, true, true]
              && tidyEnabled("架空\n文字") == [false, true, false], "整えて貼るは変わるものだけ押せる")
        let imgMenu = strip.menu(for: Clip(kind: .image, text: "", sig: ""))
        check(!imgMenu.items.contains { $0.title == "整えて貼る" || $0.title == "書式なしで貼る" }, "画像には整える・書式なしを出さない")
        check(Card.ago(Date().addingTimeInterval(-125)) == "2分前" && Card.ago(Date()) == "今", "いつ（何分前）")

        // アイコン
        check(AppIcon.png(64).count > 500 && AppIcon.menuImage().isTemplate, "アイコンを描ける")

        print(ok ? "自己テスト OK" : "自己テスト ✗ あり")
        return ok
    }

    /// 架空の中身で帯を描いて PNG に（見た目の確認用）。<出力.png>（-dark を付けると暗い版も）
    static func shot(_ out: String) {
        let (store, _, dir) = sandbox()
        defer { try? FileManager.default.removeItem(at: dir) }
        let b = store.addBoard("定型文"); _ = store.addBoard("仕事")
        let f = dir.appendingPathComponent("架空の見積もり.pdf"); try? Data().write(to: f)
        let img = NSImage(size: NSSize(width: 640, height: 400), flipped: false) { r in
            NSColor(srgbRed: 0.88, green: 0.90, blue: 0.92, alpha: 1).setFill(); r.fill()
            NSColor(srgbRed: 0.69, green: 0.44, blue: 0.15, alpha: 1).setFill(); NSBezierPath(ovalIn: NSRect(x: 220, y: 100, width: 200, height: 200)).fill()
            return true
        }
        let rep = NSBitmapImageRep(data: img.tiffRepresentation!)!
        let now = Date()
        let named = store.add(Captured(kind: .text, text: "〒000-0000 架空県架空市1-2-3"), now: now.addingTimeInterval(-3 * 86400))
        store.add(Captured(kind: .text, text: "いつもお世話になっております。架空商事の見本です。資料は前日までにお送りします。"), now: now.addingTimeInterval(-86400))
        store.add(Captured(kind: .file, text: f.path, app: "com.apple.finder", appName: "Finder"), now: now.addingTimeInterval(-7200))
        store.add(Captured(kind: .image, text: "", png: rep.representation(using: .png, properties: [:]), width: 640, height: 400), now: now.addingTimeInterval(-1800))
        store.add(Captured(kind: .link, text: "https://example.com/menu/lunch", app: "com.apple.Safari", appName: "Safari"), now: now.addingTimeInterval(-300))
        store.add(Captured(kind: .text, text: "会議は14時から第2会議室で", app: "com.apple.Notes", appName: "メモ"), now: now.addingTimeInterval(-20))
        store.pin(named.id, to: b.id)
        for dark in [false, true] {
            let strip = Strip(store: store)
            strip.panel.appearance = NSAppearance(named: dark ? .darkAqua : .aqua)
            strip.reload()
            strip.layout(width: 1440)
            strip.select(0)
            let v = strip.panel.contentView!
            v.layoutSubtreeIfNeeded()
            v.subviews.forEach { $0.needsDisplay = true }
            let r = v.bitmapImageRepForCachingDisplay(in: v.bounds)!
            v.cacheDisplay(in: v.bounds, to: r)
            let path = dark ? out.replacingOccurrences(of: ".png", with: "-dark.png") : out
            try? r.representation(using: .png, properties: [:])?.write(to: URL(fileURLWithPath: path))
            print("→ \(path)")
        }
    }
}

